"""Generate lean/SimpleAuctions/CertData.lean from data/ub_certificate.json.  Run: python make_lean_data.py"""
import json
from ub_certificate import *
I=json.load(open('../data/ub_certificate.json')); AN,SN=I['AN'],I['SN']
tab=table(AN,SN,I['grid']); Vmax=I['grid'][-1]
o=["import SimpleAuctions.CertKernel","/-! Generated by `code/make_lean_data.py` from `data/ub_certificate.json`. -/","namespace SimpleAuctions","namespace UBCert",""]
CH=60; parts=[]
for i in range(0,len(tab),CH):
    n='tab%d'%(i//CH); parts.append(n)
    o.append("def %s : List Cell :=\n  [%s]\n"%(n,",\n   ".join("(%d,%d,%d,%d)"%c for c in tab[i:i+CH])))
o.append("def tab : List Cell :=\n  "+" ++ (".join(parts)+")"*(len(parts)-1)+"\n")
o.append("def Vmax : Nat := %d"%Vmax)
o.append("def kap : Nat := %d"%I['kap'])
o.append("/-- `g = 0.1187`, scaled by `SC` -/\ndef gCap : Nat := 118700000000")
o.append("/-- `b` in units `1/UN` -/\ndef bCap : Nat := %d"%I['b'])
L=I['levels']; assert L[0][0]==0
o.append("def al0 : Nat := %d"%L[0][1])
o.append("def levels : List (Nat × Nat) :=\n  [%s]\n"%", ".join("(%d,%d)"%tuple(x) for x in L[1:]))
for i,t in enumerate(I['tan']):
    assert t['xs'][0]==1000
    o.append("def xs%d : List Nat := [%s]"%(i,", ".join(map(str,t['xs'][1:]))))
def m(nm,vals): o.append("def %s (i : Fin 4) : Nat := match i with\n  | 0 => %d | 1 => %d | 2 => %d | 3 => %d"%((nm,)+tuple(vals)))
m('y0n',[t['y0'][0] for t in I['tan']]); m('y0d',[t['y0'][1] for t in I['tan']]); m('bn',[t['b'] for t in I['tan']]); m('kn',[t['k'] for t in I['tan']])
o+=["","end UBCert","end SimpleAuctions"]
open('../lean/SimpleAuctions/CertData.lean','w',encoding='utf8').write("\n".join(o)+"\n")
print(len(tab),'cells',len(L),'levels',[len(t['xs']) for t in I['tan']])
